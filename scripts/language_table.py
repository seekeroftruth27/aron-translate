"""Write docs/languages.md, the full language support table, from languages.py.

    python scripts/language_table.py

Run it again whenever a Model is measured or a voice list changes; the table is
never edited by hand.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import languages as L

OUT = os.path.join(os.path.dirname(HERE), "docs", "languages.md")

# Measured Models, in menu order, with the picker ids that use each list.
MODELS = [
    ("gpt-6-sol", "GPT-6 Sol", "gpt-6-sol, gpt-6-sol-fast"),
    ("gpt-6.1-terra", "GPT-6.1 Terra", "gpt-6.1-terra, gpt-6.1-terra-fast"),
    ("gemini-3.5-flash-lite", "Gemini 3.5 Flash Lite", "gemini-3.5-flash-lite"),
    ("claude-haiku-4-5", "Claude Haiku 4.5", "claude-haiku-4-5"),
]
VOICES = [
    ("Soniox TTS", lambda c: L.can_speak("soniox", None, c)),
    ("ElevenLabs v3 / v4 / v4 Turbo", lambda c: L.can_speak("elevenlabs", "eleven_v4", c)),
    ("ElevenLabs Multilingual v2", lambda c: L.can_speak("elevenlabs", "eleven_multilingual_v2", c)),
    ("ElevenLabs Flash / Turbo v2.5", lambda c: L.can_speak("elevenlabs", "eleven_flash_v2_5", c)),
]


def cell(model, code):
    m = L.MEASURED[model]
    if code in m["natural"]:
        return "●"
    if code in m["rough"]:
        return "◐"
    if code in L.LAUNCH_29:
        return "○"
    return ""


def main():
    codes = sorted(L.CAPTION, key=lambda c: L.CAPTION[c])
    head = (["Language", "Code", "Heard by Soniox", "Soniox translation"]
            + [name for _, name, _ in MODELS] + ["Other Models"]
            + [name for name, _ in VOICES])
    rows = []
    for c in codes:
        heard = "✓" if c in L.HEARD else ""
        rows.append([L.CAPTION[c], f"`{c}`", heard, heard]
                    + [cell(m, c) for m, _, _ in MODELS]
                    + ["✓" if c in L.LAUNCH_29 else ""]
                    + ["✓" if can(c) else "" for _, can in VOICES])
    totals = (["**Total**", "", str(len(L.HEARD)), str(len(L.HEARD))]
              + [f"**{len(L.caption_languages(m))}** ({len(L.MEASURED[m]['natural'])} ●)"
                 for m, _, _ in MODELS]
              + [str(len(L.LAUNCH_29))]
              + [str(sum(1 for c in codes if can(c))) for _, can in VOICES])

    lines = [
        "# Supported languages",
        "",
        "<!-- Generated by scripts/language_table.py from scripts/languages.py. Do not edit by hand. -->",
        "",
        "Áron works with three separate language lists:",
        "",
        "- **Heard**: what the preacher may speak. This is Soniox's realtime speech",
        "  recognition (stt-rt-v5). The same 60 languages are what Soniox's own",
        "  translation (**none, fast** and the Router) can write, and the only ones a",
        "  bilingual pair can use.",
        "- **Captioned**: what a translator Model can write on the screen. Each Model was",
        "  measured on a real English sermon passage (2 Peter 1), translated caption by",
        "  caption through the app's own code. Two judges from other model families",
        "  named the language and rated its fluency.",
        "- **Spoken**: what each text-to-speech voice can say. A language that is",
        "  captioned but has no voice is shown on screen and not spoken.",
        "",
        "## Legend",
        "",
        "| Mark | Meaning |",
        "|---|---|",
        "| ● | **Natural**: both judges rated it 4 or 5 out of 5 in the right language. |",
        "| ◐ | **Rough**: both judges rated it at least 3: understandable, word for word. Offered in the app. |",
        "| ○ | Kept from the original 29 although it measured below rough (no language in use was taken away). |",
        "| ✓ | Supported (provider's own list, not measured). |",
        "| blank | Not offered with that Model or voice. |",
        "",
        "Picker ids per measured Model: "
        + "; ".join(f"{name}: {ids}" for _, name, ids in MODELS) + ".",
        "**Other Models** (Sonnet 5.5, Haiku 5.5, Luna, the other Gemini and Grok",
        "models) are not measured yet and offer the 29 languages the app has",
        "captioned since launch.",
        "",
        "## Table",
        "",
        "| " + " | ".join(head) + " |",
        "|" + "|".join("---" if i < 2 else ":-:" for i in range(len(head))) + "|",
    ]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    lines += ["| " + " | ".join(totals) + " |", ""]
    lines += [
        "## Notes",
        "",
        "- Measurements: `validation/results/2026-10-25-caption-languages/` (Terra added",
        "  2026-10-26). 152 languages were tried; Q'eqchi' failed with every Model and",
        "  is left out.",
        "- The passage was English. Captions from other source languages were not",
        "  measured separately.",
        "- LLM judges of low-resource languages are themselves uncertain; two families",
        "  agreeing is the safeguard, not a native reader.",
        "- Soniox translation and the voice lists come from the providers (read",
        "  2026-10-25), not from this measurement.",
        "- Chinese (Traditional) is spoken by the voices' Chinese voice, so each voice",
        "  total here is one more than the provider's own count.",
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(rows)} languages")


if __name__ == "__main__":
    main()
